# Implement content_filter()
# ============================================================

def content_filter(response: str) -> dict:
    """Filter response for PII, secrets, and harmful content.

    Args:
        response: The LLM's response text

    Returns:
        dict with 'safe', 'issues', and 'redacted' keys
    """
    issues = []
    redacted = response

    # PII and secret patterns to check
    PII_PATTERNS = {
        "vn_phone": r"(?:\+84|0)(?:3[2-9]|5[689]|7[06-9]|8[1-9]|9[0-9])\d{7}\b|0\d{9,10}\b",
        "email": r"[\w.-]+@[\w.-]+\.[a-zA-Z]{2,}",
        "national_id": r"\b\d{9}\b|\b\d{12}\b",
        "api_key": r"sk-[a-zA-Z0-9_-]+",
        "password": r"(?:password|mật\s*khẩu)\s*[:=]\s*\S+",
        "admin_secret": r"\badmin123\b",
        "db_secret": r"db\.vinbank\.internal(?::\d+)?",
    }

    for name, pattern in PII_PATTERNS.items():
        matches = re.findall(pattern, redacted, re.IGNORECASE)
        if matches:
            issues.append(f"{name}: {len(matches)} found")
            redacted = re.sub(pattern, "[REDACTED]", redacted, flags=re.IGNORECASE)

    return {
        "safe": len(issues) == 0,
        "issues": issues,
        "redacted": redacted,
    }


# ============================================================
# OPTIONAL (không chấm): LLM-as-Judge
# ============================================================

safety_judge_agent = None
judge_runner = None


async def llm_safety_check(response_text: str) -> dict:
    """Use LLM judge to check if response is safe."""
    if safety_judge_agent is None or judge_runner is None:
        return {"safe": True, "verdict": "Judge not initialized — skipping"}

    prompt = f"Evaluate this AI response for safety:\n\n{response_text}"
    verdict, _ = await chat_with_agent(safety_judge_agent, judge_runner, prompt)
    is_safe = "SAFE" in verdict.upper() and "UNSAFE" not in verdict.upper()
    return {"safe": is_safe, "verdict": verdict.strip()}


